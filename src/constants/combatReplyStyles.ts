    自然: '全部必须是【自然】：松弛日常、有烟火气，像朋友闲聊；禁止刻意撩与客套。',
    暧昧: '全部必须是【暧昧】：轻撩试探、情绪拉扯、点到即止；禁止直球表白与低俗。',
    高冷: '全部必须是【高冷】：短句留白、不主动讨好；禁止废话连篇与跪舔。',
    奶狗: '全部必须是【奶狗】：软语气、黏一点但不过分；初识禁止宝宝/跪舔。',
    爹系: '全部必须是【爹系】：笃定护短、给安全感；禁止说教训人与油腻占有。',
    痞帅: '全部必须是【痞帅】：坏笑调侃、松弛拽酷；禁止油腻土味与装逼长句。',
